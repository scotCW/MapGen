// Multi-sheet drawing helpers
// ---------------------------------------------------------------------------

function drawOverviewGrid(
  page: PDFPage,
  mapX: number, mapY: number, mapW: number, mapH: number,
  grid: SheetGrid,
  fontBold: PDFFont,
) {
  const { rows, cols, cells } = grid;
  const cellW = mapW / cols;
  const cellH = mapH / rows;
  const grey  = rgb(0.3, 0.3, 0.3);
  const white = rgb(1, 1, 1);

  // Vertical division lines
  for (let c = 1; c < cols; c++) {
    const x = mapX + c * cellW;
    for (let y = mapY; y < mapY + mapH; y += 7) {
      page.drawLine({
        start: { x, y: Math.min(y, mapY + mapH - 1) },
        end:   { x, y: Math.min(y + 4, mapY + mapH - 1) },
        thickness: 1, color: grey,
      });
    }
  }

  // Horizontal division lines
  for (let r = 1; r < rows; r++) {
    const y = mapY + (rows - r) * cellH;
    for (let x = mapX; x < mapX + mapW; x += 7) {
      page.drawLine({
        start: { x: Math.min(x, mapX + mapW - 1), y },
        end:   { x: Math.min(x + 4, mapX + mapW - 1), y },
        thickness: 1, color: grey,
      });
    }
  }

  // Cell reference labels
  for (const cell of cells) {
    const cx = mapX + cell.col * cellW + cellW / 2;
    const cy = mapY + (rows - 1 - cell.row) * cellH + cellH / 2;
    const lbl = cell.ref;
    const lw = fontBold.widthOfTextAtSize(lbl, 14);
    const lh = 14;

    // Drop shadow / background
    page.drawRectangle({
      x: cx - lw / 2 - 3, y: cy - 2,
      width: lw + 6, height: lh + 4,
      color: white, borderColor: grey, borderWidth: 0.4,
    });
    page.drawText(lbl, {
      x: cx - lw / 2, y: cy,
      font: fontBold, size: lh, color: rgb(0.1, 0.1, 0.1),
    });
  }
}

function drawEdgeMatchMarkers(
  page: PDFPage,
  mapX: number, mapY: number, mapW: number, mapH: number,
  cell: SheetCell,
  font: PDFFont,
) {
  const grey = rgb(0.3, 0.3, 0.3);
  const sz   = 6.5;
  const PAD  = 3;

  // Standard-14 PDF fonts (Helvetica here) are WinAnsi-encoded and cannot
  // render arrow glyphs (U+2190..U+2193) — pdf-lib throws at drawText() for
  // any sheet with a neighbor in any direction, which is nearly every sheet
  // in a multi-sheet layout. Verified against pdf-lib's actual encoder: `^`
  // `v` `<` `>` are plain ASCII and always safe.
  if (cell.north) {
    const lbl = `^ Sheet ${cell.north}`;
    const lw  = font.widthOfTextAtSize(lbl, sz);
    page.drawText(lbl, { x: mapX + mapW / 2 - lw / 2, y: mapY + mapH + PAD, font, size: sz, color: grey });
  }
  if (cell.south) {
    const lbl = `v Sheet ${cell.south}`;
    const lw  = font.widthOfTextAtSize(lbl, sz);
    page.drawText(lbl, { x: mapX + mapW / 2 - lw / 2, y: mapY - sz - PAD, font, size: sz, color: grey });
  }
  if (cell.west) {
    const lbl = `< Sheet ${cell.west}`;
    page.drawText(lbl, { x: mapX - font.widthOfTextAtSize(lbl, sz) - PAD, y: mapY + mapH / 2 - sz / 2, font, size: sz, color: grey });
  }
  if (cell.east) {
    const lbl = `> Sheet ${cell.east}`;
    page.drawText(lbl, { x: mapX + mapW + PAD, y: mapY + mapH / 2 - sz / 2, font, size: sz, color: grey });
  }
}

function drawIndexInset(
  page: PDFPage,
  x: number, y: number,
  grid: SheetGrid,
  current: SheetCell,
  font: PDFFont,
) {
  const { rows, cols } = grid;
  const insetH  = Math.min(SCALE_H - 6, 48);
  const insetW  = Math.round(insetH * (cols / rows));
  const cellW   = insetW / cols;
  const cellH   = insetH / rows;

  const grey  = rgb(0.75, 0.75, 0.75);
  const hi    = rgb(0.18, 0.44, 0.76);
  const black = rgb(0, 0, 0);
  const white = rgb(1, 1, 1);

  // Background
  page.drawRectangle({ x, y, width: insetW, height: insetH, color: white, borderColor: black, borderWidth: 0.5 });

  for (const cell of grid.cells) {
    const cx = x + cell.col * cellW;
    const cy = y + (rows - 1 - cell.row) * cellH;
    const isThis = cell.row === current.row && cell.col === current.col;

    page.drawRectangle({
      x: cx, y: cy, width: cellW, height: cellH,
      color: isThis ? hi : grey,
      borderColor: black, borderWidth: 0.3,
    });

    if (cellW > 10) {
      const lbl = cell.ref;
      const lw  = font.widthOfTextAtSize(lbl, 4);
      page.drawText(lbl, {
        x: cx + cellW / 2 - lw / 2, y: cy + cellH / 2 - 2,
        font, size: 4, color: isThis ? white : black,
      });
    }
  }
}
