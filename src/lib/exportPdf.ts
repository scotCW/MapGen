const DEFAULT_OVERLAP_IN = 0.5;

export interface MultiSheetPdfOptions extends Omit<CartographicPdfOptions, "mapJpegUrl" | "bounds"> {
  rasterLayers: RasterLayer[];
  overlapIn?: number;
  dpi?: number;
  onProgress?: (detail: string, current: number, total: number) => void;
}

export async function buildMultiSheetPdf(opts: MultiSheetPdfOptions): Promise<Uint8Array> {
  const { fmt, scale, rasterLayers, legendEntries } = opts;
  const overlapIn = opts.overlapIn ?? DEFAULT_OVERLAP_IN;
  const DPI = opts.dpi ?? 150;

  const grid = computeSheetGrid(fmt, overlapIn, opts.centerLng, opts.centerLat, scale);
  const { mapWidthIn, mapHeightIn, totalBounds, cells, totalSheets } = grid;

  const paper    = effectivePaper(fmt);
  const pageW    = paper.w   * PT_PER_IN;
  const pageH    = paper.h   * PT_PER_IN;
  const marginPt = (MARGIN_SIZES[fmt.margins] ?? 0.5) * PT_PER_IN;
  const usableW  = pageW - marginPt * 2;
  const usableH  = pageH - marginPt * 2;

  const discY   = marginPt;
  const scaleY  = discY  + DISC_H + DISC_SCALE_GAP_PT;
  const mapY    = scaleY + SCALE_H;
  const mapH    = usableH - TITLE_H - SCALE_H - DISC_H - DISC_SCALE_GAP_PT;
  const mapX    = marginPt;
  const mapW    = usableW;

  const pixelW = Math.round(mapWidthIn  * DPI);
  const pixelH = Math.round(mapHeightIn * DPI);

  const now     = new Date();
  const dateStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
  const decl    = getMagneticDeclination(opts.centerLat, opts.centerLng, 0, currentDecimalYear());

  const doc      = await PDFDocument.create();
  doc.setTitle(opts.projectName);
  doc.setCreator("Hunting Map Generator");
  doc.setProducer("pdf-lib");

  const font     = await doc.embedFont(StandardFonts.Helvetica);
  const fontBold = await doc.embedFont(StandardFonts.HelveticaBold);

  // total progress = 1 overview + N sheets
  const totalSteps = 1 + totalSheets;

  // ── Page 1: Overview sheet ─────────────────────────────────────────────────
  opts.onProgress?.("Rendering overview sheet…", 0, totalSteps);

  const ovPixelW = Math.round(mapWidthIn  * grid.cols * DPI);
  const ovPixelH = Math.round(mapHeightIn * grid.rows * DPI);
  const ovJpeg   = await renderMapImage({ bounds: totalBounds, pixelW: ovPixelW, pixelH: ovPixelH, rasterLayers });

  const ovPage = doc.addPage([pageW, pageH]);
  ovPage.drawRectangle({ x: 0, y: 0, width: pageW, height: pageH, color: rgb(1, 1, 1) });

  const ovB64     = ovJpeg.split(",")[1] ?? "";
  const ovBytes   = Uint8Array.from(atob(ovB64), (c) => c.charCodeAt(0));
  const ovImage   = await doc.embedJpg(ovBytes);
  ovPage.drawImage(ovImage, { x: mapX, y: mapY, width: mapW, height: mapH });

  // Grid overlay on overview
  drawOverviewGrid(ovPage, mapX, mapY, mapW, mapH, grid, fontBold);
  drawNeatline(ovPage, mapX, mapY, mapW, mapH);

  drawTitleBlock(ovPage, {
    x: mapX, y: mapY + mapH, width: mapW, height: TITLE_H,
    title: opts.projectName,
    subtitle: `${opts.subtitle}   |   Overview — ${totalSheets} sheets`,
    scale, dateStr, sheetRef: `1 of ${totalSheets + 1}`,
    font, fontBold,
  });
  drawScaleBar(ovPage, { x: mapX + 8, y: scaleY, font, scale, pageWidthPt: mapW });
  drawDisclaimerBlock(ovPage, mapX, discY, mapW, DISC_H, ACCESS_DISCLAIMER, font, fontBold);

  // ── Pages 2..N: individual sheets ─────────────────────────────────────────
  for (let i = 0; i < cells.length; i++) {
    const cell = cells[i];
    opts.onProgress?.(
      `Rendering sheet ${cell.ref} (${i + 1} of ${totalSheets})…`,
      i + 1,
      totalSteps,
    );

    const jpegUrl = await renderMapImage({ bounds: cell.bounds, pixelW, pixelH, rasterLayers });
    const b64     = jpegUrl.split(",")[1] ?? "";
    const jBytes  = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
    const jImage  = await doc.embedJpg(jBytes);

    const page = doc.addPage([pageW, pageH]);
    page.drawRectangle({ x: 0, y: 0, width: pageW, height: pageH, color: rgb(1, 1, 1) });
    page.drawImage(jImage, { x: mapX, y: mapY, width: mapW, height: mapH });

    drawLatLonGrid(page, { mapX, mapY, mapW, mapH, bounds: cell.bounds, font });
    drawNeatline(page, mapX, mapY, mapW, mapH);

    drawCompassRose(page, {
      cx: mapX + mapW - ROSE_R - 8,
      cy: mapY + mapH - ROSE_R - 8,
      radius: ROSE_R,
      declDeg: decl,
      font, fontBold,
    });

    drawEdgeMatchMarkers(page, mapX, mapY, mapW, mapH, cell, font);

    drawTitleBlock(page, {
      x: mapX, y: mapY + mapH, width: mapW, height: TITLE_H,
      title: opts.projectName,
      subtitle: `${opts.subtitle}   |   Sheet ${cell.ref}`,
      scale, dateStr,
      sheetRef: `Sheet ${cell.ref} — Page ${cell.pageIndex} of ${totalSheets + 1}`,
      font, fontBold,
    });

    drawScaleBar(page, { x: mapX + 8, y: scaleY, font, scale, pageWidthPt: mapW });

    const LEGEND_W = Math.min(140, mapW * 0.28);
    drawLegend(page, { x: mapX + mapW - LEGEND_W - 4, y: scaleY, width: LEGEND_W, entries: legendEntries, font, fontBold });

    drawIndexInset(page, mapX + mapW - LEGEND_W - 80, scaleY, grid, cell, font);

    drawDisclaimerBlock(page, mapX, discY, mapW, DISC_H, ACCESS_DISCLAIMER, font, fontBold);
  }

  return doc.save();
}

